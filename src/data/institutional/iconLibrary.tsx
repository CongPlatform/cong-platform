const iconById = new Map<string, InstitutionalIconDefinition>(
  institutionalIcons.map((item) => [item.id, item]),
);

const legacyAliases: Record<string, string> = {
  star: "sparkles",
  map: "map-pin",
};

export function getInstitutionalIconDefinition(
  value: unknown,
): InstitutionalIconDefinition {
  const raw = typeof value === "string" ? value : "heart";
  return iconById.get(legacyAliases[raw] ?? raw) ?? iconById.get("heart")!;
}

export function filterInstitutionalIcons(
  query: string,
  category: InstitutionalIconCategory = "all",
): InstitutionalIconDefinition[] {
  const normalized = query.trim().toLocaleLowerCase("pt-BR");
  return institutionalIcons.filter((item) => {
    if (category !== "all" && item.category !== category) return false;
    if (!normalized) return true;
    return `${item.label} ${item.id} ${item.keywords.join(" ")}`
      .toLocaleLowerCase("pt-BR")
      .includes(normalized);
  });
}
